import { createRequire } from 'module';
const require = createRequire(import.meta.url);
const { chromium } = require('playwright');
const url = process.env.URL ?? 'http://localhost:5173/';
const out = process.env.OUT ?? 'e2e/out';
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 760 } });
const errors = [];
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
page.on('console', (m) => { if (m.type() === 'error') errors.push('console: ' + m.text()); });
await page.goto(url);
await page.waitForSelector('#btn-new', { timeout: 20000 });
await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}/01-title.png` });
await page.click('#btn-new');
await page.waitForSelector('#cc-name');
await page.fill('#cc-name', 'Akira');
await page.click('[data-weapon="gravity_hammer"]');
await page.waitForTimeout(800);
await page.screenshot({ path: `${out}/02-creator.png` });
await page.click('#cc-start');
await page.waitForTimeout(2500);
await page.screenshot({ path: `${out}/03-city.png` });
console.log('errors:', JSON.stringify(errors, null, 1));
await browser.close();
